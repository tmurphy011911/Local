// The update prompts speak in Bo's voice, generated by Claude and typewritered
// with a coral cursor — the same aesthetic as the returning-user splash (see
// SplashScreen.ReturningSplash / SplashGreetingService). While Claude resolves
// the line, Bo sits with a blinking cursor; on timeout the service hands back a
// static Bo line so the prompt is never blocked on the network.
private const val UPDATE_LINE_TIMEOUT_PASSIVE_MS = 2000L
private const val UPDATE_LINE_TIMEOUT_ACTIVE_MS = 3000L
private const val UPDATE_CHAR_DELAY_MS = 34L
private const val UPDATE_CURSOR_BLINK_MS = 450L

// Static safety net if the Koin service can't be reached at all (the service
// itself already falls back to a Bo line on a slow/failed Claude call).
private const val PASSIVE_HARD_FALLBACK = "New version's out. Worth the tap"
private const val ACTIVE_HARD_FALLBACK = "This version's a bit behind. Update and we're back in"

/**
 * Fetch Bo's line once (bounded by [timeoutMs] inside the service) and hold it.
 * Starts blank so the prompt shows Bo + a blinking cursor while Claude works,
 * then swaps in the resolved line for the typewriter. [fallback] covers the
 * (unexpected) case where the service isn't registered.
 */
@Composable
private fun rememberBoUpdateLine(tone: UpdateTone, timeoutMs: Long, fallback: String): String {
    val service = remember {
        runCatching { KoinPlatform.getKoin().get<UpdateGreetingService>() }.getOrNull()
    }
    var line by remember { mutableStateOf("") }
    LaunchedEffect(tone) {
        line = service?.line(tone, timeoutMs)?.takeIf { it.isNotBlank() } ?: fallback
    }
    return line
}

/**
 * Typewriter state for [line]: returns the currently-revealed substring and the
 * on/off state of the continuously-blinking cursor. Re-types whenever the line
 * changes (keyed on it), so the blank→resolved swap types the real line out
 * exactly once.
 */
@Composable
private fun rememberTypedLine(line: String): Pair<String, Boolean> {
    var revealed by remember(line) { mutableStateOf(0) }
    LaunchedEffect(line) {
        revealed = 0
        while (revealed < line.length) {
            delay(UPDATE_CHAR_DELAY_MS)
            revealed++
        }
    }
    var cursorOn by remember { mutableStateOf(true) }
    LaunchedEffect(Unit) {
        while (true) {
            cursorOn = true
            delay(UPDATE_CURSOR_BLINK_MS)
            cursorOn = false
            delay(UPDATE_CURSOR_BLINK_MS)
        }
    }
    return line.take(revealed) to cursorOn
}

/** Build the typed text + trailing coral cursor block as one annotated string. */
private fun typedWithCursor(typed: String, cursorOn: Boolean, textColor: Color) =
    buildAnnotatedString {
        withStyle(SpanStyle(color = textColor)) { append(typed) }
        // Cursor is always in the string (width never jitters) but only painted
        // coral on the "on" half of the blink.
        withStyle(SpanStyle(color = if (cursorOn) AppColors.Coral else Color.Transparent)) {
            append("▏")
        }
    }

/**
 * Dismissable banner for the soft update nudge. Shows below the header on the
 * home page. Bo (ghost) delivers a Claude-generated, typewritered line in his
 * voice instead of the old static "A new version is available" copy.
 */
@Composable
fun UpdateAvailableBanner(
    onUpdate: () -> Unit,
    onDismiss: () -> Unit,
) {
    val line = rememberBoUpdateLine(UpdateTone.Passive, UPDATE_LINE_TIMEOUT_PASSIVE_MS, PASSIVE_HARD_FALLBACK)
    val (typed, cursorOn) = rememberTypedLine(line)

    Row(
        modifier = Modifier
            .fillMaxWidth()
            .background(AppColors.CoralLt)
            .clickable(onClick = onUpdate)
            .padding(horizontal = 16.dp, vertical = 10.dp),
        verticalAlignment = Alignment.CenterVertically,
    ) {
        Image(
            painter = painterResource(Res.drawable.bo_tiny),
            contentDescription = null,
            modifier = Modifier.size(20.dp),
        )
        Spacer(Modifier.width(10.dp))
        Text(
            text = typedWithCursor(typed, cursorOn, AppColors.Ink2),
            style = TextStyle(fontFamily = AppFonts.Body, fontWeight = FontWeight.SemiBold, fontSize = 12.sp, color = AppColors.Ink2),
            maxLines = 1,
            softWrap = false,
            modifier = Modifier.weight(1f),
        )
        Spacer(Modifier.width(8.dp))
        Text(
            "Update",
            style = TextStyle(fontFamily = AppFonts.Body, fontWeight = FontWeight.ExtraBold, fontSize = 11.sp, color = Color.White),
            modifier = Modifier
                .background(AppColors.Coral, RoundedCornerShape(8.dp))
                .padding(horizontal = 10.dp, vertical = 5.dp),
        )
        Spacer(Modifier.width(8.dp))
        Icon(
            Icons.Outlined.Close,
            contentDescription = "Dismiss",
            modifier = Modifier
                .size(16.dp)
                .clickable(
                    interactionSource = remember { MutableInteractionSource() },
                    indication = null,
                    onClick = onDismiss,
                ),
            tint = AppColors.Ink3,
        )
    }
}

/**
 * Full-screen force update blocker. Prevents all app usage until the user
 * updates. Bo (ghost) delivers a Claude-generated, typewritered line in his
 * voice, matching the returning-splash aesthetic.
 *
 * @param message the server's `force_message` (from app_config). Bo's generated
 *   line takes precedence; this is used as the fallback if Claude doesn't answer
 *   in time, so any server-specified guidance still surfaces.
 */
@Composable
fun ForceUpdateScreen(
    message: String,
    onUpdate: () -> Unit,
) {
    val fallback = message.ifBlank { ACTIVE_HARD_FALLBACK }
    val line = rememberBoUpdateLine(UpdateTone.Active, UPDATE_LINE_TIMEOUT_ACTIVE_MS, fallback)
    val (typed, cursorOn) = rememberTypedLine(line)

    Box(
        modifier = Modifier
            .fillMaxSize()
            .background(AppColors.Cream),
        contentAlignment = Alignment.Center,
    ) {
        Column(
            modifier = Modifier.padding(horizontal = 32.dp),
            horizontalAlignment = Alignment.CenterHorizontally,
        ) {
            // Bo + his line, centered as a group. Short lines cluster in the
            // middle; a long line wraps within the remaining width beside Bo.
            Row(
                modifier = Modifier.fillMaxWidth(),
                horizontalArrangement = Arrangement.Center,
                verticalAlignment = Alignment.CenterVertically,
            ) {
                Image(
                    painter = painterResource(Res.drawable.bo_tiny),
                    contentDescription = null,
                    modifier = Modifier.size(40.dp),
                )
                Spacer(Modifier.width(14.dp))
                Text(
                    text = typedWithCursor(typed, cursorOn, AppColors.Ink2),
                    style = TextStyle(
                        fontFamily = AppFonts.Body,
                        fontWeight = FontWeight.SemiBold,
                        fontSize = 17.sp,
                        color = AppColors.Ink2,
                        lineHeight = 24.sp,
                    ),
                    textAlign = TextAlign.Start,
                )
            }

            Spacer(Modifier.height(36.dp))

            DuoButton(
                title = "Update Now",
                primary = true,
                onClick = onUpdate,
                modifier = Modifier.fillMaxWidth(),
            )
        }
    }
}
