package live.localapp.local.domain.model

/**
 * Structured response shapes returned by Bo via the Phase-6 tools
 * (present_suggestions, present_event_brief, present_venue_brief,
 * present_quick_fact, present_scope_redirect).
 *
 * Each tool produces one of these. ChatScreen renders the matching
 * Compose component inline in the message stream.
 */
sealed interface BoStructuredResponse {

    /** present_suggestions — multi-event grouped browsing tray. */
    data class Suggestions(
        val headline: String,
        val groupBy: GroupBy,
        val groups: List<Group>,
        val footer: Footer? = null,
    ) : BoStructuredResponse {
        enum class GroupBy { DAY, CATEGORY, NONE }

        data class Group(
            val label: String,
            val events: List<EventRef>,
        )

        /** event_id + Bo's reason for picking it. Client hydrates the rest from EventRepository. */
        data class EventRef(
            val eventId: String,
            val rationale: String?,
        )

        data class Footer(
            val text: String?,
            val actions: List<Action>,
        )

        enum class Action {
            SEARCH_WIDER, DIFFERENT_CATEGORY, LATE_NIGHT, DIFFERENT_DAY, MORE_RESULTS;
            companion object {
                fun fromString(s: String?): Action? = when (s) {
                    "search_wider" -> SEARCH_WIDER
                    "different_category" -> DIFFERENT_CATEGORY
                    "late_night" -> LATE_NIGHT
                    "different_day" -> DIFFERENT_DAY
                    "more_results" -> MORE_RESULTS
                    else -> null
                }
            }
        }
    }

    /** present_event_brief — single event with a direct answer line. */
    data class EventBrief(
        val eventId: String,
        val answerLine: String,
    ) : BoStructuredResponse

    /** present_venue_brief — single venue + upcoming events. */
    data class VenueBrief(
        val venueName: String,
        val answerLine: String?,
        val upcomingEventIds: List<String>,
    ) : BoStructuredResponse

    /** present_quick_fact — one-line answer with optional tap-target. */
    data class QuickFact(
        val text: String,
        val ctaEventId: String?,
    ) : BoStructuredResponse

    /** present_scope_redirect — out-of-scope decline + redirect chips. */
    data class ScopeRedirect(
        val explanation: String,
        val redirectChips: List<Chip>,
    ) : BoStructuredResponse {
        data class Chip(val label: String, val intent: String)
    }
}

/**
 * One event in the cross-message draft tray. The user adds events from any
 * SuggestionTray / EventBriefCard / VenueBriefCard via the [+] button; the
 * tray persists across Bo turns until the user taps Build, which sends the
 * full event_id list back to Bo as a structured prompt.
 *
 * Fields are denormalized at add-time so the tray renders without re-fetching
 * the full Event row. The eventId is the canonical reference for plan-build.
 */
data class DraftTrayEvent(
    val eventId: String,
    val title: String,
    val startAt: String?,            // ISO 8601 from event row, source of truth for slot dates
    val timeLabel: String,           // pre-formatted "8 PM" / "Time TBD"
    val dateLabel: String,           // "Sat May 25"
    val venueName: String?,
    val category: String?,
    val subcategory: String?,
    val imageUrl: String?,
    val isFree: Boolean,
)

/**
 * Chip computed by the client from the current tray state. Tapping fires a
 * structured intent message back to Bo (no free-text typing). Generated by
 * [DraftTrayChipGenerator] from contextual rules — never from Bo.
 */
data class DraftTrayChip(
    val label: String,
    val intent: String,         // pre-filled message to Bo
    val priority: Int,          // 1 = most useful, lower = lower priority
    val category: ChipCategory,
)

enum class ChipCategory { MEAL, COMPANION, GAP_FILLER, EXPANSION, BUILD, DIVERSITY }
