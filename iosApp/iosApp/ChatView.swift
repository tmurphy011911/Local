// MARK: - Chat View

struct ChatView: View {
    @StateObject private var state = ChatState()
    @State private var inputText = ""
    @FocusState private var inputFocused: Bool
    /// Event IDs the user has tapped [+] on this session — drives the build CTA.
    /// Tapping + also saves the event to Saved Events the first time (handled
    /// by the bridge). Cleared on Start over.
    @State private var selectedEventIds: Set<String> = []
    /// Selected day tab in the draft drawer when picks span multiple days.
    @State private var draftDayIndex: Int = 0
    /// Snapshot of `selectedEventIds` at the moment the user last tapped the
    /// Build CTA. The CTA hides whenever the current selection equals this
    /// snapshot (idempotent — same set already submitted). It reappears the
    /// instant the user adds or removes any card. Cleared on Start over.
    @State private var lastSubmittedSelection: Set<String> = []
    /// Events the user dismissed (✕) from the results. View-only filter across
    /// all suggestion trays this session; cleared on Start over.
    @State private var dismissedEventIds: Set<String> = []
    /// Per-(messageId, groupKey) loading flags for the Find-more tile. Set
    /// when the user taps Find more, cleared when ChatBridge.onLoadMoreFinished
    /// fires for that key.
    @State private var loadingGroupKeys: Set<String> = []
    /// Per-(messageId, groupKey) flags for "no more results" — tile becomes
    /// disabled once the well runs dry to prevent repeat taps.
    @State private var exhaustedGroupKeys: Set<String> = []
    /// AI text-bubble IDs whose typewriter animation has finished. New AI
    /// messages reveal char-by-char on first appearance; once typed, they
    /// stay static so re-renders / scrolling don't replay the animation.
    @State private var typedMessageIds: Set<String> = []

    /// Editable location chip — opens a sheet when tapped, lets the user
    /// change the search scope. The chip value is the canonical scope Bo
    /// uses on every search.
    @State private var showLocationEditor: Bool = false

    /// Gates the on-open intent sheet until just after this view (itself a
    /// presented sheet) finishes appearing — presenting a nested sheet during
    /// the parent's present animation can silently no-op on first open.
    @State private var intentReady: Bool = false

    /// Live measurement of the "content height below the latest user bubble's
    /// top edge" inside the chat ScrollView — i.e. the latest user bubble's
    /// own height plus any AI items rendered below it. Driven by a
    /// PreferenceKey attached to the latest user message AND to the content
    /// end sentinel; the spacer subtracts this from the viewport to size
    /// itself exactly. With this, scrollTo(.top) on the latest user bubble
    /// places it at the viewport top with NO over-scroll room beyond.
    @State private var heightBelowLatestUser: CGFloat = 0
    @State private var latestUserBubbleY: CGFloat = 0
    @State private var contentEndY: CGFloat = 0
    // Generation token for the bottom-follow retry loop. Bumped each time a
    // follow is (re)started so stale loops from a prior token cancel out.
    @State private var followGen: Int = 0
    // Bumped (throttled) by the typewriter as it reveals chars. The final
    // reply is typed client-side — no streaming/message-count change fires as
    // it grows — so this is what drives bottom-following during the animation.
    @State private var typewriterTick: Int = 0
    // Bottom edge (maxY) of the latest AI text bubble, in "chatScroll" space
    // (origin = viewport top). Measured directly on the bubble — which IS
    // rendered — so it's reliable even when the bubble overflows the fold.
    // (`contentEndY`'s sentinel is the LAST LazyVStack child, which isn't laid
    // out while off-screen, so it can't detect overflow — the bug that kept
    // the follow from firing.) Overflow ⟺ lastAiBubbleMaxY > viewport height.
    @State private var lastAiBubbleMaxY: CGFloat = 0
    let onDismiss: () -> Void
    let showUpgradeBanner: Bool
    let onUpgrade: () -> Void

    init(onDismiss: @escaping () -> Void, showUpgradeBanner: Bool = false, onUpgrade: @escaping () -> Void = {}) {
        self.onDismiss = onDismiss
        self.showUpgradeBanner = showUpgradeBanner
        self.onUpgrade = onUpgrade
    }

    /// ID of the most recent USER message, or nil if the user hasn't sent
    /// anything yet. Drives the ChatGPT-style scroll anchor: whenever this
    /// changes, we scroll so the corresponding bubble sits at the top of
    /// the viewport.
    private var lastUserMessageId: String? {
        state.messages.last(where: { $0.isUser })?.id
    }

    /// ID of the most recent plan card, or nil if none yet. The plan card is
    /// not a user message, so the user-bubble anchor above never moves it.
    /// We anchor on this separately so a freshly built (or updated) plan card
    /// snaps to the top of the viewport instead of landing wherever the prior
    /// scroll left it — otherwise a tall card sits scrolled off the top with
    /// a viewport of dead space beneath it.
    private var lastPlanCardId: String? {
        state.messages.last(where: { $0.isPlanCard })?.id
    }

    /// ID of the most recent PRESENTATION card — either a plan/day card
    /// (`isPlanCard`) OR a structured suggestion tray (`structured != nil`,
    /// e.g. "This week in Media"). Neither is a user message, so the
    /// user-bubble anchor never moves them. A structured tray previously had
    /// NO anchor at all, so a second tray sent after history built up just
    /// appended below the fold — the user saw it peeking in at the very
    /// bottom edge, unreadable (the reported bug). Anchoring this to the top
    /// of the viewport brings the whole freshly-arrived card on screen.
    private var lastPresentationCardId: String? {
        state.messages.last(where: { $0.isPlanCard || $0.structured != nil })?.id
    }

    /// ID of the most recent settled AI *text* reply (not a card/tray, not a
    /// user bubble). We attach a bottom-edge geometry reader to only this row
    /// so a single measurement drives the bottom-follow.
    private var lastAiTextMessageId: String? {
        state.messages.last(where: { !$0.isUser && !$0.isPlanCard && $0.structured == nil })?.id
    }

    /// Follow the bottom of a growing/long reply, ChatGPT-style.
    ///
    /// A single deferred check is unreliable: `contentEndY` / `latestUserBubbleY`
    /// are updated by `onGeometryChange` only AFTER the closure runs, and a new
    /// message animates in over 0.22s — so an immediate measurement reads the
    /// pre-layout `below` (<= viewport), the overflow guard fails, and nothing
    /// scrolls (the "still not autoscrolling" bug). Android dodges this by
    /// retrying in a loop until layout settles; we mirror that here.
    ///
    /// We poll for ~1.5s (every 60ms). On each tick, IFF the content below the
    /// anchored user bubble exceeds the viewport (i.e. the reply overflowed),
    /// we pin the target's bottom to the viewport bottom. The overflow guard is
    /// what keeps SHORT replies untouched: while they fit, `below <= v`, so the
    /// user bubble stays anchored at the top. A `followGen` token cancels any
    /// loop still running from a previous reply/token.
    private func startBottomFollow(
        geo: GeometryProxy,
        proxy: ScrollViewProxy,
        targetId: String
    ) {
        followGen += 1
        let myGen = followGen
        func tick(_ attempt: Int) {
            guard attempt < 26 else { return }       // ~26 * 60ms ≈ 1.6s budget
            DispatchQueue.main.asyncAfter(deadline: .now() + 0.06) {
                guard myGen == followGen else { return }  // superseded — stop
                let v = geo.size.height
                let below = contentEndY - latestUserBubbleY
                if below > v {
                    // Non-animated so continuous following (token-by-token)
                    // reads as a smooth scroll rather than stacked animations.
                    proxy.scrollTo(targetId, anchor: .bottom)
                }
                tick(attempt + 1)
            }
        }
        tick(0)
    }

    // Trailing-spacer height is now a constant fraction of viewport. The
    // earlier "dynamic collapse" logic (tall while Bo is in-flight, 16pt
    // once Bo finished) caused the prior exchange to snap back into view
    // when Bo's response settled: the spacer shrinking dropped total
    // content height below the viewport, so the ScrollView had no choice
    // but to re-clamp scroll position to the natural top — undoing the
    // anchor. A constant moderate-height spacer keeps the anchor stable
    // AND limits over-scroll to roughly half a viewport, not infinity.

    var body: some View {
        VStack(spacing: 0) {
            chatHeader

            if showUpgradeBanner {
                upgradeBanner
            }

            // Messages — ChatGPT-style scroll anchor.
            //
            // Previous behavior auto-scrolled to .bottom on every state
            // change (new message, streaming text, isSearching, quickReplies).
            // That kept the WHOLE thread visible at the bottom of the
            // viewport, so prior history stayed on screen forever and the
            // current exchange never "owned" the screen.
            //
            // New behavior: on a new USER message we scroll so that user
            // bubble sits at the TOP of the viewport. Prior history scrolls
            // off the top (still reachable by swiping up). Bo's response
            // streams in below the anchored user bubble. We do NOT re-scroll
            // on streaming text, isSearching, isTyping, or quickReplies —
            // those would yank the user's bubble out from under their gaze.
            //
            // The trailing spacer (`Color.clear.frame(height: viewport)`)
            // gives the ScrollView enough scrollable room for a short user
            // bubble to actually anchor at the top — without it, SwiftUI
            // clamps the scroll to the natural content height and the bubble
            // lands wherever it can.
            // 16pt gap between the location banner's bottom divider and the
            // top of the ScrollView viewport. Padding goes on the OUTER
            // container (not on the LazyVStack inside the ScrollView) —
            // padding inside the ScrollView scrolls off the top when the
            // anchored user bubble snaps to .top.
            GeometryReader { geo in
                ScrollViewReader { proxy in
                    ScrollView {
                        LazyVStack(alignment: .leading, spacing: 12) {
                            ForEach(state.messages, id: \.id) { message in
                                Group {
                                    if message.isPlanCard {
                                        planCardRow(message)
                                    } else if let suggestions = message.structured {
                                        suggestionTrayRow(messageId: message.id, suggestions: suggestions)
                                    } else {
                                        messageRow(message)
                                    }
                                }
                                .id(message.id)
                                // Measure the latest user bubble's top-edge Y
                                // in scroll coordinates. We only attach to THE
                                // latest user message so only one geometry
                                // reader contributes to the preference key.
                                .background(
                                    Group {
                                        if message.isUser && message.id == lastUserMessageId {
                                            GeometryReader { proxy in
                                                Color.clear
                                                    .onGeometryChange(for: CGFloat.self) { p in
                                                        p.frame(in: .named("chatScroll")).minY
                                                    } action: { newY in
                                                        latestUserBubbleY = newY
                                                    }
                                            }
                                        } else if message.id == lastAiTextMessageId {
                                            // Bottom edge of the latest AI text
                                            // bubble. Measured here (on the
                                            // rendered row) — not via the lazy
                                            // bottom sentinel — so it reflects
                                            // the true bottom even when the
                                            // reply runs past the viewport.
                                            GeometryReader { proxy in
                                                Color.clear
                                                    .onGeometryChange(for: CGFloat.self) { p in
                                                        p.frame(in: .named("chatScroll")).maxY
                                                    } action: { newMaxY in
                                                        lastAiBubbleMaxY = newMaxY
                                                    }
                                            }
                                        }
                                    }
                                )
                                .transition(.asymmetric(
                                    insertion: .opacity.combined(with: .move(edge: .bottom)),
                                    removal: .opacity
                                ))
                            }
                            .animation(.easeOut(duration: 0.22), value: state.messages.count)

                            // Mutually exclusive, matching Compose priority:
                            // searching (idiom) > streaming text > typing dots.
                            if state.isSearching {
                                searchingIndicator.id("searching")
                            } else if !state.streamingText.isEmpty {
                                aiMessageBubble(state.streamingText)
                                    .id("streaming")
                            } else if state.isTyping {
                                typingIndicator.id("typing")
                            }

                            // Sentinel that measures the bottom edge of all
                            // content above the trailing spacer. Combined
                            // with latestUserBubbleY, we know exactly how
                            // much real content sits below the latest user
                            // bubble's top, so the spacer can be sized to
                            // (viewport - that height) — giving the anchor
                            // enough scroll range with ZERO over-scroll past
                            // the natural end of content.
                            Color.clear
                                .frame(height: 0)
                                .onGeometryChange(for: CGFloat.self) { p in
                                    p.frame(in: .named("chatScroll")).minY
                                } action: { newY in
                                    contentEndY = newY
                                }

                            // Dynamic trailing spacer. Math:
                            //   heightBelowBubble = contentEndY - latestUserBubbleY
                            //   spacer = viewport - heightBelowBubble
                            // Result: max scroll position = latestUserBubbleY,
                            // meaning the user can scroll the bubble exactly
                            // to viewport top and no further.
                            // While we're still measuring (first layout pass
                            // or pre-first-message), fall back to a viewport-
                            // tall spacer so the anchor works.
                            Color.clear
                                .frame(height: {
                                    let v = geo.size.height
                                    let below = contentEndY - latestUserBubbleY
                                    if latestUserBubbleY <= 0 || below <= 0 { return v }
                                    return max(16, v - below)
                                }())
                                .id("trailingSpacer")
                        }
                        .padding(.horizontal, 14)
                        .padding(.top, 4)
                        .padding(.bottom, 8)
                    }
                    .coordinateSpace(name: "chatScroll")
                    .onChange(of: lastUserMessageId) { newId in
                        guard let id = newId else { return }
                        // Wait one frame so SwiftUI has laid out the new row
                        // before we ask the ScrollView to anchor to it.
                        DispatchQueue.main.async {
                            withAnimation(.easeOut(duration: 0.25)) {
                                proxy.scrollTo(id, anchor: .top)
                            }
                        }
                        // Collapse the keyboard so Bo's reply is fully visible.
                        inputFocused = false
                    }
                    .onChange(of: state.messages.count) { _ in
                        // Dismiss keyboard when a plan card arrives so the card
                        // isn't fighting the keyboard for vertical space.
                        if state.messages.last?.isPlanCard == true {
                            inputFocused = false
                        }
                        // Catch-up follow: when a long text reply settles out
                        // of streaming into the message list, the streaming
                        // follow below stops (streamingText empties). If that
                        // reply overflowed the viewport, pin its bottom so the
                        // newest text stays on screen. Only for plain AI text —
                        // cards are top-anchored by lastPresentationCardId.
                        let last = state.messages.last
                        // Only follow within a real exchange. The opening
                        // greeting (and the post–Start-over greeting) has no
                        // preceding user bubble, so `latestUserBubbleY` is stale
                        // and `below` inflates — bottom-follow then yanks the
                        // full-height greeting down and it snaps back on settle
                        // (the ~100px jump). A greeting just sits at the top.
                        if let last, !last.isUser, !last.isPlanCard, last.structured == nil,
                           lastUserMessageId != nil {
                            startBottomFollow(geo: geo, proxy: proxy, targetId: last.id)
                        }
                    }
                    .onChange(of: lastPresentationCardId) { newId in
                        guard let id = newId else { return }
                        // Defer two runloops: one for SwiftUI to lay out the
                        // new (tall) card row, one more so the dynamic trailing
                        // spacer at .id("trailingSpacer") has settled to its
                        // clamped height before we anchor — otherwise a stale
                        // spacer height makes scrollTo land short.
                        DispatchQueue.main.async {
                            DispatchQueue.main.async {
                                withAnimation(.easeOut(duration: 0.25)) {
                                    proxy.scrollTo(id, anchor: .top)
                                }
                            }
                        }
                    }
                    // Follow the bottom as Bo's reply streams in (ChatGPT-style).
                    // The user bubble is anchored to the top on send and we
                    // intentionally don't re-scroll for SHORT replies. But once
                    // the reply grows TALLER than the viewport it runs off the
                    // bottom edge with nothing pulling the newest tokens into
                    // view (the reported "Bo kept chatting past where I could
                    // see" bug). While streaming, if the content below the
                    // anchored user bubble exceeds the viewport, keep the
                    // streaming bubble's bottom pinned to the viewport bottom.
                    .onChange(of: state.streamingText) { newText in
                        // Restart the retry-follow loop on each streamed chunk.
                        // The loop's overflow guard keeps short replies anchored
                        // at the top; once the streaming bubble grows past the
                        // viewport it pins the newest text to the bottom.
                        // Same guard as the settle-follow above: don't follow
                        // the opening greeting's stream (no user anchor →
                        // spurious scroll). Greetings are 1–2 short sentences
                        // and never overflow, so nothing needs pinning.
                        guard !newText.isEmpty, lastUserMessageId != nil else { return }
                        startBottomFollow(geo: geo, proxy: proxy, targetId: "streaming")
                    }
                    .onChange(of: typewriterTick) { _ in
                        // Follow the client-side typewriter as it reveals text.
                        // Overflow is detected from the bubble's own measured
                        // bottom edge (reliable past the fold), NOT the lazy
                        // bottom sentinel. While the bubble's bottom sits below
                        // the viewport, pin it to the viewport bottom so the
                        // newest line stays visible. Short replies that fit
                        // (maxY <= viewport) never scroll → they stay top-
                        // anchored under the user bubble.
                        guard let id = lastAiTextMessageId else { return }
                        // Small slack so we don't fight sub-pixel jitter.
                        if lastAiBubbleMaxY > geo.size.height + 1 {
                            proxy.scrollTo(id, anchor: .bottom)
                        }
                    }
                }
            }
            // 16pt OUTSIDE the ScrollView so the viewport itself starts
            // below the banner with breathing room. Padding inside the
            // ScrollView would scroll off-screen when the user bubble
            // anchors to .top.
            .padding(.top, 16)

            // Create plan CTA (hidden during celebration). Shown when the
            // user has tapped [+] on 1+ events in a SuggestionTray AND the
            // current selection differs from what was last submitted (so the
            // bar dismisses immediately after Build).
            if !selectedEventIds.isEmpty
                && selectedEventIds != lastSubmittedSelection
                && !state.showPlanSuccess {
                draftDrawer
                    .transition(.move(edge: .bottom).combined(with: .opacity))
            }

            // Quick replies (hidden during celebration)
            if !state.quickReplies.isEmpty && !state.showPlanSuccess {
                quickRepliesRow
            }

            // Suggestion-card follow-up chips ("Search wider" / "Different day"
            // / "Different category") intentionally removed from under results to
            // save vertical space — chips now only appear on the first prompt
            // (intent) and the create-plan confirmation (both via quickReplies).
            // `suggestionFooterRow` / `latestSuggestionFooter` are retained but
            // unused; the same actions remain reachable by typing.

            // Input bar (hidden during celebration)
            if !state.showPlanSuccess {
                inputBar
            }
        }
        .background(C.snow)
        .overlay {
            if state.showPlanSuccess {
                PlanCelebrationOverlay(
                    days: state.days,
                    attendeeCount: state.planAttendeeCount,
                    onSharePlan: {
                        // Fire the system share sheet for the plan we just
                        // saved. Do NOT clear the success overlay — the user
                        // can still tap View Plans or Home after sharing.
                        ChatBridge.shared.sharePlan?()
                    },
                    onViewPlans: {
                        // CRITICAL: drop the Bo input focus / collapse the keyboard
                        // BEFORE tearing down the chat and presenting the native plan
                        // detail. If the chat TextField stays first responder through
                        // the tab-switch + sheet-dismiss + plan-detail present, SwiftUI
                        // keeps recomputing its focused caret rect / intrinsic size
                        // mid-transition and spins the main thread in TextField layout
                        // until the watchdog kills the app (0x8BADF00D "View Plan crash").
                        inputFocused = false
                        UIApplication.shared.sendAction(#selector(UIResponder.resignFirstResponder), to: nil, from: nil, for: nil)

                        // First: switch to Plans tab and dismiss chat. Second:
                        // open the just-saved plan's detail sheet so the user
                        // lands directly on it rather than the list. The
                        // Kotlin viewSavedPlan binding fetches the plan and
                        // calls showNativePlanDetail; brief delay so the tab
                        // switch + sheet dismiss complete first.
                        let savedId = state.lastSavedPlanId
                        TabBarBridge.shared.onTabSelected?(KotlinInt(integerLiteral: 2))
                        ChatBridge.shared.clearSuccessState?()
                        onDismiss()
                        if !savedId.isEmpty {
                            DispatchQueue.main.asyncAfter(deadline: .now() + 0.45) {
                                ChatBridge.shared.viewSavedPlan?(savedId)
                            }
                        }
                    }
                )
            }
        }
        .onAppear {
            ChatBridge.shared.onStateUpdate = { snapshot in
                state.update(from: snapshot)
            }
            ChatBridge.shared.onLoadMoreFinished = { messageId, groupKey, addedCount in
                let key = loadKey(messageId: messageId as String, groupKey: groupKey as String)
                let added = Int(truncating: addedCount)
                DispatchQueue.main.async {
                    loadingGroupKeys.remove(key)
                    if added == 0 {
                        exhaustedGroupKeys.insert(key)
                    }
                }
            }
            // Hydrate the typewriter-completed set from the app-lifetime
            // store. Without this, every reopen of the chat sheet replays
            // the typewriter animation for every prior AI message because
            // `@State private var typedMessageIds` resets to empty on view
            // recreation. The store survives the view, so previously-typed
            // messages render statically immediately.
            typedMessageIds = TypewriterCompletionStore.shared.completed
            // Let the parent sheet's present animation settle before the
            // intent sheet tries to present on top.
            DispatchQueue.main.asyncAfter(deadline: .now() + 0.45) {
                intentReady = true
            }
        }
        .sheet(isPresented: $showLocationEditor) {
            SearchScopeEditorSheet(
                currentName: state.currentLocationName,
                currentCoord: state.currentCoord,
                currentRadiusMiles: state.searchRadiusMiles,
                placeholder: state.scopeEditorPlaceholder,
                onConfirm: { name, lat, lng, radius in
                    // Send the geocoded coords too — Kotlin's hardcoded
                    // geocodeCity only knows ~30 metros and silently fails
                    // on arbitrary places like "Concord, MA". Apple's
                    // CLGeocoder handles those; we just forward its result.
                    // Kotlin/Native erases Double in lambda params, so wrap.
                    ChatBridge.shared.setSearchScopeWithCoords?(
                        name,
                        KotlinDouble(value: lat),
                        KotlinDouble(value: lng),
                        KotlinDouble(value: radius),
                    )
                    showLocationEditor = false
                }
            )
        }
        // (Intent sheet removed — Bo's opening greeting already asks the same
        // "looking for something / planning / browsing?" question in prose, so
        // the modal picker was redundant. `BoIntentSheet` retained but unused.)
    }

