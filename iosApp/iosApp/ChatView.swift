                    Image(systemName: mode == .list ? "list.bullet" : "map")
                        .font(.system(size: 12, weight: .bold))
                        .foregroundColor(active ? .white : STC.ink3)
                        .frame(width: 42, height: 26)
                        .background(active ? STC.coral : Color.clear)
