// MARK: - Typewriter Completion Store
//
// `ChatView` is built fresh every time the chat sheet is presented. Its
// `@State private var typedMessageIds` therefore resets to empty on every
// open — which meant every prior AI message failed the "already typed"
// check and replayed its TypewritingAiBubble animation. The chat looked
// like it was re-streaming the entire conversation on every reopen.
//
// This singleton outlives any single `ChatView` instance, so once a
// message's typewriter finishes we record it here. On reopen, `.onAppear`
// hydrates the local `@State` set from this store, so previously-typed
// messages render via the static `aiMessageBubble` path immediately.
//
// Cleared by "Start over" alongside the in-view set so a reset chat
// animates from scratch.
@MainActor
final class TypewriterCompletionStore {
    static let shared = TypewriterCompletionStore()
    var completed: Set<String> = []
    private init() {}
}

// MARK: - Observable State

class ChatState: ObservableObject {
    @Published var messages: [ChatMessageSnapshot] = []
    @Published var quickReplies: [QuickReplySnapshot] = []
    @Published var streamingText: String = ""
    @Published var isTyping: Bool = false
    @Published var isSearching: Bool = false
    /// Ordered, human-readable steps for the searching indicator, derived from
    /// Bo's tool args (e.g. "Searching within 20 miles of Waltham"). Empty =
    /// the indicator falls back to the rotating gerunds.
    @Published var searchingNarration: [String] = []
    /// Hyperlocal "searching" idioms for the user's set location, generated by
    /// Claude (e.g. "Taking the Broad Street Line..."). The searching indicator
    /// interleaves one every ~3rd rotation. Empty = generic gerunds only.
    @Published var localIdioms: [String] = []
    @Published var isBusy: Bool = false
    @Published var inputEnabled: Bool = true
    @Published var showPlanSuccess: Bool = false
    @Published var days: [DaySnapshot] = []
    @Published var weather: [KotlinInt: WeatherSnapshot] = [:]
    /// Total people on the plan (creator + invitees). Drives the post-save
    /// celebration's Share Plan CTA copy. Defaults to 1 (solo) so the label
    /// reads sensibly before the first state snapshot arrives.
    @Published var planAttendeeCount: Int = 1
    /// ID of the just-saved plan — used by the celebration's "View Plan"
    /// link to deep-link to the plan detail page after switching tabs.
    @Published var lastSavedPlanId: String = ""
    /// Canonical search scope — drives the editable location banner in the
    /// chat header.
    @Published var currentLocationName: String = ""
    /// Geocoded coordinates for the named scope. nil when the name didn't
    /// resolve — the editor falls back to a Boston-area default region.
    @Published var currentCoord: CLLocationCoordinate2D? = nil
    /// Radius in miles. Drives the slider + the MapCircle overlay.
    @Published var searchRadiusMiles: Double = 20.0
    /// Region-aware placeholder text for the scope-editor's city field.
    @Published var scopeEditorPlaceholder: String = "e.g. a city or neighborhood"
    // The goal picked from the intent sheet ("find_events"/"create_plan"/
    // "browsing"), or "" when not yet chosen. Empty drives the intent sheet.
    @Published var boIntent: String = ""
    // Saved (favorited) event ids — drives the filled ❤️ and the build CTA.
    @Published var favoriteEventIds: Set<String> = []

    func update(from snapshot: ChatStateSnapshot) {
        DispatchQueue.main.async { [weak self] in
            self?.messages = snapshot.messages
            self?.quickReplies = snapshot.quickReplies
            self?.streamingText = snapshot.streamingText
            self?.isTyping = snapshot.isTyping
            self?.isSearching = snapshot.isSearching
            self?.searchingNarration = snapshot.searchingNarration
            self?.isBusy = snapshot.isBusy
            self?.inputEnabled = snapshot.inputEnabled
            self?.showPlanSuccess = snapshot.showPlanSuccess
            self?.days = snapshot.days
            self?.weather = snapshot.weather
            self?.planAttendeeCount = Int(snapshot.planAttendeeCount)
            self?.lastSavedPlanId = snapshot.lastSavedPlanId
            self?.currentLocationName = snapshot.currentLocationName
            self?.localIdioms = snapshot.localIdioms
            self?.currentCoord = snapshot.hasLocationCoords
                ? CLLocationCoordinate2D(latitude: snapshot.currentLat, longitude: snapshot.currentLng)
                : nil
            self?.searchRadiusMiles = snapshot.searchRadiusMiles
            self?.scopeEditorPlaceholder = snapshot.scopeEditorPlaceholder
            self?.boIntent = snapshot.boIntent
            self?.favoriteEventIds = Set(snapshot.favoriteEventIds.map { $0 as String })
        }
    }
}

