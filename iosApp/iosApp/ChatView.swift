            .padding(.top, 14)
            .onChange(of: radiusMiles) { _, _ in
                cameraPosition = .region(fittingRegion)
            }
            .onChange(of: center.latitude) { _, _ in
                cameraPosition = .region(fittingRegion)
            }

            HStack(spacing: 12) {
