                            AsyncImage(url: u) { img in
                                img.resizable().aspectRatio(contentMode: .fill)
                            } placeholder: { Color.clear }
                        }
                    }
                    .frame(width: 60, height: 60)
                    .clipShape(RoundedRectangle(cornerRadius: 10))

