// MARK: - Searching Indicator (rotating gerunds, fade transition)

private struct SearchingIndicatorView: View {
    /// Completed narration steps derived from Bo's tool args. They stack up and
    /// persist; the gerund typewriter below is the live "thinking" line.
    let narration: [String]
    /// Hyperlocal idioms for the user's location; interleaved every ~3rd
    /// rotation. Empty = generic gerunds only.
    var localIdioms: [String] = []

    @State private var phraseIndex: Int = Int.random(in: 0..<searchingPhrases.count)
    @State private var revealCount: Int = 0
    @State private var opacity: Double = 1.0
    @State private var caretOn: Bool = true
    // The phrase currently being typed out, pinned for the whole rotation. We
    // CANNOT derive the displayed text from `fullPhrase` directly: `fullPhrase`
    // depends on `localIdioms`, which arrives asynchronously from Bo mid-search.
    // If that update lands while a rotation is typing, `fullPhrase` would flip
    // to a longer idiom while the typewriter only reveals up to the OLD phrase's
    // length — freezing the idiom half-shown (the "cut off halfway" bug). By
    // snapshotting the phrase into @State at the start of each rotation and
    // reading the display from it, an async idiom update only takes effect on
    // the NEXT rotation, so every phrase types out in full.
    @State private var activePhrase: String = ""
    // Staggered reveal: a batch of steps arrives at once after the round
    // finishes, so reveal them one at a time. Persists across appends.
    @State private var visibleSteps: Int = 0

    // Every ~3rd rotation, surface a hyperlocal idiom for the user's location
    // (when Claude has generated some) to forge a place-specific connection;
    // otherwise fall back to the generic whimsical gerunds.
    private var fullPhrase: String {
        if !localIdioms.isEmpty && phraseIndex % 3 == 2 {
            return localIdioms[(phraseIndex / 3) % localIdioms.count]
        }
        return searchingPhrases[phraseIndex % searchingPhrases.count]
    }
    private var revealed: String {
        let chars = Array(activePhrase)
        return String(chars.prefix(min(revealCount, chars.count)))
    }

    var body: some View {
        // Two stacked rows sharing ONE leftmost avatar column:
        //  • the narration block (Bo + checked steps) — only once steps exist
        //  • the live idiom line (Bo + gerund) — always present while searching
        // Because each row's Bo is the first element of its own HStack, the
        // idiom Bo lines up directly beneath the narration Bo. When there are
        // no steps yet, only the idiom row renders → a single Bo.
        VStack(alignment: .leading, spacing: 6) {
            // Guard on the ACTUAL revealed steps, not just `visibleSteps > 0`:
            // visibleSteps is persistent @State, so when narration is empty (or
            // shorter than a stale visibleSteps) the prefix is empty and we'd
            // otherwise render the narration Bo with no content beside it — a
            // lone Bo floating above the idiom line.
            if !narration.prefix(visibleSteps).isEmpty {
                HStack(alignment: .top, spacing: 8) {
                    Image("BoTiny")
                        .resizable()
                        .aspectRatio(contentMode: .fit)
                        .frame(width: 20, height: 20)
                        .padding(.top, 1)
                    VStack(alignment: .leading, spacing: 6) {
                        // Completed steps, each with a check, fading in as they arrive.
                        ForEach(Array(narration.prefix(visibleSteps).enumerated()), id: \.offset) { _, step in
                            HStack(alignment: .firstTextBaseline, spacing: 6) {
                                Text("✓")
                                    .font(F.body(12, .bold))
                                    .foregroundColor(C.ink3.opacity(0.5))
                                Text(step)
                                    .font(F.body(13, .semibold))
                                    .foregroundColor(C.ink3.opacity(0.7))
                            }
                            .transition(.opacity)
                        }
                    }
                }
            }
            // Live "thinking" line — always present while searching. Its Bo
            // shares the leftmost column with the narration Bo above, so once
            // steps appear it sits directly beneath that Bo.
            HStack(alignment: .center, spacing: 8) {
                // Bo stays put the whole time — only the idiom text fades and
                // re-appears as phrases rotate. Applying `opacity` to this whole
                // row (as it used to) made Bo blink out with every rotation.
                Image("BoTiny")
                    .resizable()
                    .aspectRatio(contentMode: .fit)
                    .frame(width: 20, height: 20)
                HStack(alignment: .firstTextBaseline, spacing: 1) {
                    Text(revealed)
                        .font(F.body(14, .semibold))
                        .foregroundColor(C.ink3)
                    Text("▍")
                        .font(F.body(14, .semibold))
                        .foregroundColor(C.coral)
                        .opacity(caretOn ? 1 : 0)
                }
                .opacity(opacity)
            }
        }
        .padding(.vertical, 2)
        .animation(.easeOut(duration: 0.3), value: visibleSteps)
        .task(id: narration) {
            // Clamp first: when a new turn clears/shrinks narration, persistent
            // @State visibleSteps could be ahead of the current count, which
            // would render a lone narration Bo with no step beside it.
            if visibleSteps > narration.count { visibleSteps = narration.count }
            // Advance the reveal one step at a time up to the current count.
            while visibleSteps < narration.count {
                try? await Task.sleep(nanoseconds: 700_000_000)
                if Task.isCancelled { return }
                visibleSteps += 1
            }
        }
        .task(id: localIdioms) {
            // Typewriter loop for the gerund line: reveal chars at ~28ms, hold,
            // fade, rotate to the next gerund. Slight per-char jitter.
            //
            // The `id: localIdioms` is load-bearing, not cosmetic. `localIdioms`
            // is a plain stored property (not @State), so a bare `.task` would
            // capture whatever it was on FIRST appearance — which is EMPTY,
            // because Bo generates the idioms asynchronously a beat after the
            // searching indicator shows. A bare task keeps running with that
            // frozen empty array forever, so `fullPhrase`'s `phraseIndex % 3 == 2`
            // idiom branch can never fire and idioms never appear (the bug).
            // Keying the task on `localIdioms` restarts the loop once, when the
            // idioms land, so the closure re-captures the populated array.
            while !Task.isCancelled {
                opacity = 1.0
                revealCount = 0
                // Snapshot the phrase for this whole rotation so an async
                // `localIdioms` arrival can't swap it mid-type (see activePhrase).
                activePhrase = fullPhrase
                let chars = Array(activePhrase)
                for i in 1...max(chars.count, 1) {
                    let jitter = UInt64.random(in: 0...20_000_000)
                    try? await Task.sleep(nanoseconds: 26_000_000 + jitter)
                    if Task.isCancelled { return }
                    revealCount = i
                }
                try? await Task.sleep(nanoseconds: 1_400_000_000)
                if Task.isCancelled { return }
                withAnimation(.easeIn(duration: 0.18)) { opacity = 0 }
                try? await Task.sleep(nanoseconds: 220_000_000)
                if Task.isCancelled { return }
                phraseIndex += 1
            }
        }
        .task {
            // Caret blink — independent loop so it keeps blinking after typing
            // finishes during the hold + fade phase.
            while !Task.isCancelled {
                try? await Task.sleep(nanoseconds: 480_000_000)
                if Task.isCancelled { return }
                caretOn.toggle()
            }
        }
    }
